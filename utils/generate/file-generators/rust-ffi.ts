import { writeFileSync } from 'fs';
import { resolve } from 'path';
import functions from '../functions';
import { iLog } from '../log';

// Generate the raw `extern "C"` declarations of the mojibake-sys crate.

export type RustFFIArg = {
  type: string;
  name: string;
};

export type RustFFIFunction = {
  comment: string;
  nodiscard: boolean;
  ret: string;
  name: string;
  args: RustFFIArg[];
  variadic: boolean;
};

const MAX_WIDTH = 100;

const RUST_KEYWORDS = new Set([
  'abstract', 'as', 'async', 'await', 'become', 'box', 'break', 'const', 'continue', 'crate',
  'do', 'dyn', 'else', 'enum', 'extern', 'false', 'final', 'fn', 'for', 'gen', 'if', 'impl', 'in',
  'let', 'loop', 'macro', 'match', 'mod', 'move', 'mut', 'override', 'priv', 'pub', 'ref',
  'return', 'self', 'Self', 'static', 'struct', 'super', 'trait', 'true', 'try', 'type',
  'typeof', 'unsafe', 'unsized', 'use', 'virtual', 'where', 'while', 'yield'
]);

// C types that map to core::ffi aliases.
const FFI_TYPES: Record<string, string> = {
  'char': 'c_char',
  'int': 'c_int',
  'unsigned int': 'c_uint',
  'void': 'c_void'
};

// C types that map to Rust primitives.
const PRIMITIVE_TYPES: Record<string, string> = {
  'bool': 'bool',
  'size_t': 'usize',
  'int32_t': 'i32',
  'uint8_t': 'u8',
  'uint32_t': 'u32'
};

function rustType(cType: string, ffiTypes: Set<string>): string {
  const type = cType.trim();

  if(type.endsWith('*')) {
    let base = type.slice(0, -1).trim();
    const isConst = base.startsWith('const ');

    if(isConst) {
      base = base.slice('const '.length).trim();
    }

    return `${isConst ? '*const' : '*mut'} ${rustType(base, ffiTypes)}`;
  }

  if(FFI_TYPES[type] !== undefined) {
    ffiTypes.add(FFI_TYPES[type]);

    return FFI_TYPES[type];
  }

  if(PRIMITIVE_TYPES[type] !== undefined) {
    return PRIMITIVE_TYPES[type];
  }

  // Mojibake types are declared by hand in lib.rs. C enums are `c_int` aliases.
  if(/^mjb_[a-z0-9_]+$/.test(type)) {
    return type;
  }

  throw new Error(`Rust FFI: unsupported C type "${cType}"`);
}

function rustName(name: string): string {
  return RUST_KEYWORDS.has(name) ? `${name}_` : name;
}

// A function is bound unless it is variadic or takes a va_list, which stable Rust cannot declare.
function isBindable(fn: RustFFIFunction): boolean {
  return !fn.variadic && !fn.args.some(arg => arg.type.trim() === 'va_list');
}

function formatFunction(fn: RustFFIFunction, ffiTypes: Set<string>): string {
  const lines: string[] = [`    /// ${fn.comment}`];

  if(fn.nodiscard) {
    lines.push('    #[must_use]');
  }

  const ret = fn.ret.trim() === 'void' ? '' : ` -> ${rustType(fn.ret, ffiTypes)}`;
  const args = fn.args.map(arg => `${rustName(arg.name)}: ${rustType(arg.type, ffiTypes)}`);
  const oneLine = `    pub fn ${fn.name}(${args.join(', ')})${ret};`;

  // Match rustfmt: one line when it fits, otherwise one argument per line.
  if(oneLine.length <= MAX_WIDTH || args.length === 0) {
    lines.push(oneLine);
  } else {
    lines.push(`    pub fn ${fn.name}(`);

    for(const arg of args) {
      lines.push(`        ${arg},`);
    }

    lines.push(`    )${ret};`);
  }

  return lines.join('\n');
}

export function formatRustFFI(fns: RustFFIFunction[]): string {
  const ffiTypes = new Set<string>();
  const bound = fns.filter(isBindable);
  const skipped = fns.filter(fn => !isBindable(fn)).map(fn => `// - ${fn.name}`);
  const body = bound.map(fn => formatFunction(fn, ffiTypes)).join('\n\n');
  const imports = [...ffiTypes].sort();

  return `// The Mojibake library
//
// This file is distributed under the MIT License. See LICENSE for details.

// This file is automatically generated from utils/generate/functions.ts. Do not edit.
//
// Variadic functions and functions that take a \`va_list\` are not bound:
${skipped.join('\n')}

use core::ffi::{${imports.join(', ')}};

use super::*;

extern "C" {
${body}
}
`;
}

export function rustFFIFunctions(): RustFFIFunction[] {
  return functions.map(fn => ({
    comment: fn.comment,
    nodiscard: fn.attributes.includes('MJB_NODISCARD'),
    ret: fn.ret,
    name: fn.name,
    args: fn.args.map(arg => ({ type: arg.type, name: arg.name })),
    variadic: fn.variadic === true
  }));
}

export function generateRustFFI() {
  iLog('Generate mojibake-sys functions.rs');

  const outputPath = resolve(__dirname, '../../../src/rust/mojibake-sys/src/functions.rs');
  writeFileSync(outputPath, formatRustFFI(rustFFIFunctions()));
}
